// src/utils/model/outcomeLedger.ts
//
// Pure reader for the routing ledger at <stateDir>/ralph/ledger/outcomes.jsonl,
// where <stateDir> is .limitless (preferred) or a legacy .openclaude.
// Tolerates missing file (→ empty results) and malformed lines (→ skip).
// No caching, no fs watching — every call reads fresh.

import * as fs from 'node:fs'
import * as path from 'node:path'
import {
  LEGACY_OPENCLAUDE_DIRNAME,
  LIMITLESS_DIRNAME,
  resolveProjectStateDirname,
} from '../productStateDir.js'

// ─── Types ────────────────────────────────────────────────────────────────────

/**
 * Failure category for a non-complete dispatch.  Adopted from Kalibr's outcome
 * record design: infrastructure failures must not pollute model-quality signals.
 *
 * Vocabulary (pragmatic subset — not Kalibr's full 13):
 *   Infrastructure (NOT model-quality evidence):
 *     rate_limited   — 429 / quota exhausted; try again later
 *     auth           — 401 / invalid or expired key
 *     server_error   — 5xx / overloaded; provider is unhealthy
 *     timeout        — wall-clock limit exceeded before any response
 *   Capability (model-level, but task-size specific):
 *     context_exceeded — prompt + response would exceed model's context window;
 *                        the model genuinely could not handle the task at this size
 *   Quality (counts against success normally):
 *     quality        — model produced output but it was wrong / incomplete
 *     tool_error     — model called a tool incorrectly or misused the API
 *     other          — failure reason does not fit any above category
 */
export type FailureCategory =
  | 'rate_limited'
  | 'auth'
  | 'server_error'
  | 'timeout'
  | 'context_exceeded'
  | 'quality'
  | 'tool_error'
  | 'other'

/** One JSONL line written by openralph-hook.sh. All fields optional because
 *  the hook skips absent YAML values rather than failing. */
export type LedgerEntry = {
  ts?: string
  session_id?: string | null
  task_slug?: string | null
  persona?: string | null
  workload?: string | null
  provider_model_used?: string | null
  status?: string | null
  tests_passed?: boolean | null
  new_gaps?: number | null
  duration_s?: number | null
  /** Task category echoed from the dispatch brief. Vocabulary: implementation |
   *  debugging | research | refactoring | verification | other. Null when the
   *  brief did not carry the field.  Captured now for future per-category
   *  stratification — not yet part of the aggregation cell key so cells stay
   *  large enough to satisfy MIN_RELIABLE_N. */
  task_category?: string | null
  /** Checker verdict for this dispatch. Only non-null on openralph-checker rows.
   *  Null on all worker rows (builder, refiner, etc.) — absence is not failure.
   *  Written by the hook when `goal_met:` is present in the persona-result YAML. */
  goal_met?: boolean | null
  // ── Token usage fields (Gap 3) ──────────────────────────────────────────────
  // Extracted from AgentToolResult.usage (agentToolUtils.ts:227-258), which
  // reflects the FINAL assistant turn — a proxy, not a per-dispatch sum.
  // All null when the tool_response is not a parseable AgentToolResult JSON.
  // NOTE: do not compute dollars here — token aggregation per cell is a
  // follow-up once enough data accumulates across providers.
  /** Input tokens consumed by the final assistant turn of this dispatch. */
  input_tokens?: number | null
  /** Output tokens generated by the final assistant turn of this dispatch. */
  output_tokens?: number | null
  /** Cache-read input tokens (prompt-cache hits) for the final turn. */
  cache_read_tokens?: number | null
  /** Cache-write input tokens (new cache entries written) for the final turn. */
  cache_write_tokens?: number | null
  /** Anthropic service tier for the final turn ('standard' | 'priority' | 'batch'). */
  service_tier?: string | null
  /** Billing model inferred at write time from provider_model_used.
   *  Heuristic mirrors billingModel() in modelRegistry.ts:
   *    localhost/127.0.0.1 → 'free'
   *    anthropic-proxy prefix or codex in name → 'subscription'
   *    everything else → 'metered'
   *  Null when provider_model_used is absent. */
  billing_model?: 'subscription' | 'metered' | 'free' | null
  /**
   * Why the dispatch did not complete, when status !== 'complete'.
   * Self-reported by the persona in the persona-result YAML.
   * Null (or absent) on successful dispatches, or when the persona did not
   * classify the failure.
   *
   * Aggregation policy (see aggregateLedgerStats):
   *   - Infrastructure categories (rate_limited, auth, server_error, timeout):
   *     EXCLUDED from both n and successes — not evidence of model quality.
   *   - context_exceeded: counts as failure (the model genuinely could not handle
   *     the task at this context size).
   *   - quality / tool_error / other: count as failure normally.
   *   - Absent / null (legacy rows, pre-category data): counted as today —
   *     backward-compatible; absence is not infrastructure.
   */
  failure_category?: FailureCategory | null
}

/** A worker LedgerEntry annotated after joinCheckerVerdicts() runs.
 *  checker_goal_met is null when no checker row with a matching task_slug exists. */
export type AnnotatedLedgerEntry = LedgerEntry & {
  checker_goal_met: boolean | null
}

/** Aggregated success stats for one (persona, workload, provider_model_used) cell. */
export type LedgerStats = {
  persona: string
  workload: string
  provider_model_used: string
  /** Raw count of entries in this cell. Retained for display / back-compat. */
  n: number
  /** Raw count of successes in this cell. Retained for display / back-compat. */
  successes: number
  /** successes / n, or null when n === 0. */
  successRate: number | null
  /** mean of non-null duration_s values, or null when none recorded. */
  avgDurationS: number | null
  /**
   * Recency-weighted effective sample count, produced when RecencyOptions are
   * passed to aggregateLedgerStats.  Each entry's weight is
   *   w = 0.5 ^ (age_days / halfLifeDays)
   * so entries older than halfLifeDays contribute < 50% of full weight.
   * Null when no RecencyOptions were supplied (absent ≠ zero).
   */
  effectiveN: number | null
  /**
   * Recency-weighted effective success count (same decay applied to each
   * success indicator).  Null when no RecencyOptions were supplied.
   */
  effectiveSuccesses: number | null
  /**
   * Count of entries excluded from n/successes because they carried an
   * infrastructure failure_category (rate_limited, auth, server_error, timeout).
   * These entries are noise, not model-quality evidence, and are filtered before
   * Wilson LCB computation.  0 when no such entries exist in the cell.
   */
  infraExcluded: number
}

// ─── Constants ────────────────────────────────────────────────────────────────

/** Relative path (suffix below the product state dir) to the ledger file. */
const LEDGER_SUFFIX = 'ralph/ledger/outcomes.jsonl'

/** Canonical relative path from project root to the ledger file. */
export const LEDGER_RELATIVE_PATH = `${LIMITLESS_DIRNAME}/${LEDGER_SUFFIX}`

/** Legacy relative path read when no `.limitless` dir exists yet. */
export const LEGACY_LEDGER_RELATIVE_PATH = `${LEGACY_OPENCLAUDE_DIRNAME}/${LEDGER_SUFFIX}`

/** Minimum cell size before stats are considered reliable (epsilon-greedy
 *  exploration threshold used by resolveProviderForClass). */
export const MIN_RELIABLE_N = 3

/**
 * Wilson score lower confidence bound for a binomial proportion.
 *
 * Used as the sort key for ledger-ranked candidates (group 0) instead of
 * raw successRate, so that early-luck lock-in is dampened: a 3/3 record
 * (LCB ≈ 0.75 at z=1.0) no longer crushes a 5/8 record (LCB ≈ 0.45);
 * as n grows, LCB converges to the true rate.
 *
 * @param successes  Number of successful outcomes in the cell.
 * @param n          Total outcomes in the cell (must be > 0).
 * @param z          Normal quantile for the one-sided confidence level
 *                   (1.0 ≈ 84%, 1.28 ≈ 90%, 1.645 ≈ 95%).  Default 1.0.
 * @returns          Lower bound in [0, 1].  Returns 0 when n === 0.
 */
export function wilsonLower(successes: number, n: number, z = 1.0): number {
  if (n === 0) return 0
  const phat = successes / n
  const z2 = z * z
  const num =
    phat + z2 / (2 * n) - z * Math.sqrt(phat * (1 - phat) / n + z2 / (4 * n * n))
  const den = 1 + z2 / n
  return num / den
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

/**
 * The set of failure_category values that represent infrastructure failures —
 * provider-side problems that tell us nothing about model quality.
 *
 * Aggregation policy: entries carrying any of these categories are EXCLUDED
 * from both n and successes in aggregateLedgerStats.  They are tracked in the
 * cell's infraExcluded counter for observability but do not affect the Wilson
 * LCB that drives routing decisions.
 *
 * Compare: context_exceeded is NOT in this set — it is a capability failure
 * (the model genuinely could not do the task at that context size) and counts
 * against success normally.
 */
export const INFRA_FAILURE_CATEGORIES: ReadonlySet<FailureCategory> = new Set([
  'rate_limited',
  'auth',
  'server_error',
  'timeout',
])

/**
 * Returns true when an entry counts as a success:
 * status === 'complete' AND tests_passed !== false.
 * Mirrors the shell/python definition in openralph-route-stats.sh.
 */
export function isSuccessEntry(entry: LedgerEntry): boolean {
  return entry.status === 'complete' && entry.tests_passed !== false
}

// ─── Checker↔worker join ──────────────────────────────────────────────────────

/**
 * Join checker verdict rows to their corresponding worker rows by task_slug.
 *
 * For each worker row (persona starts with "openralph-" but does NOT end with
 * "-checker"), find the checker row(s) with the same task_slug (persona ends
 * with "-checker") and annotate the worker row with `checker_goal_met`.
 *
 * Rules:
 * - If multiple checker rows match the same task_slug, the one with the latest
 *   `ts` value wins (last-checker-wins semantics).
 * - Worker rows with no matching checker row get `checker_goal_met: null`.
 * - Checker rows themselves are not included in the output — they exist only as
 *   the verdict source.
 * - Entries that are not OpenRalph worker rows (no persona, or persona does not
 *   start with "openralph-") are returned unmodified with `checker_goal_met: null`.
 */
export function joinCheckerVerdicts(entries: LedgerEntry[]): AnnotatedLedgerEntry[] {
  // Build a map: task_slug → latest checker row (by ts, then by array order).
  const checkerBySlug = new Map<string, LedgerEntry>()
  for (const entry of entries) {
    const persona = entry.persona ?? ''
    if (!persona.endsWith('-checker')) continue
    const slug = entry.task_slug
    if (!slug) continue
    const existing = checkerBySlug.get(slug)
    // Keep the latest by ts; fall back to array order (later = wins) when ts equal.
    if (!existing || (entry.ts ?? '') >= (existing.ts ?? '')) {
      checkerBySlug.set(slug, entry)
    }
  }

  const result: AnnotatedLedgerEntry[] = []
  for (const entry of entries) {
    const persona = entry.persona ?? ''
    // Skip checker rows — they are verdict sources, not outcomes to annotate.
    if (persona.endsWith('-checker')) continue

    const slug = entry.task_slug
    let checker_goal_met: boolean | null = null
    if (slug) {
      const checker = checkerBySlug.get(slug)
      if (checker !== undefined) {
        checker_goal_met = checker.goal_met ?? null
      }
    }
    result.push({ ...entry, checker_goal_met })
  }
  return result
}

// ─── Core functions ───────────────────────────────────────────────────────────

/**
 * Read and parse outcomes.jsonl from `<projectRoot>/<stateDir>/ralph/ledger/`.
 * Returns an empty array when the file is absent.
 * Malformed lines are silently skipped.
 */
export function readLedgerEntries(projectRoot: string): LedgerEntry[] {
  // Prefer `.limitless/ralph/ledger`, falling back to an existing
  // `.openclaude/ralph/ledger` so historical routing outcomes survive.
  const ledgerPath = path.join(
    projectRoot,
    resolveProjectStateDirname(projectRoot),
    LEDGER_SUFFIX,
  )
  let raw: string
  try {
    raw = fs.readFileSync(ledgerPath, 'utf8')
  } catch {
    return []
  }

  const entries: LedgerEntry[] = []
  for (const line of raw.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed) continue
    try {
      const parsed = JSON.parse(trimmed) as LedgerEntry
      entries.push(parsed)
    } catch {
      // malformed line — skip
    }
  }
  return entries
}

/**
 * Recency decay options for aggregateLedgerStats.
 *
 * Each entry's contribution is weighted by:
 *   w = 0.5 ^ (age_days / halfLifeDays)
 * where age_days = (now - entry.ts) in days.  Entries without a parseable `ts`
 * field are treated as age = 0 (i.e. weight = 1.0) — conservative, not punitive.
 *
 * Pass `now` as a Unix-epoch millisecond timestamp (Date.now() at the call site)
 * so this function remains pure and testable without internal clock calls.
 */
export type RecencyOptions = {
  /** Half-life in days.  Default 14.  A cell entry that is exactly halfLifeDays
   *  old contributes weight 0.5; at 2× halfLifeDays it contributes 0.25, etc. */
  halfLifeDays: number
  /** Reference "now" as milliseconds since Unix epoch (e.g. Date.now()).
   *  Passed in by the caller so this function stays pure. */
  now: number
}

/** The default half-life used when RecencyOptions is constructed without
 *  an explicit halfLifeDays.  14 days balances responsiveness to provider
 *  weight changes against false positives from short-run variance. */
export const DEFAULT_HALF_LIFE_DAYS = 14

/** Options for aggregateLedgerStats. */
export type AggregateLedgerOptions = {
  /**
   * How to define "success" for the aggregation.
   *
   * - `'self'` (default): mirrors the shell definition — `status === 'complete'
   *   AND tests_passed !== false`.  No change from the existing behavior.
   * - `'checker-verified'`: counts success only when the worker row is itself a
   *   success AND has `checker_goal_met === true` (populated by joinCheckerVerdicts).
   *   Worker rows where `checker_goal_met` is null (no checker verdict found) are
   *   EXCLUDED from both numerator and denominator — absence of verification is
   *   not failure.  Pass `joinCheckerVerdicts(entries)` as the entries argument
   *   when using this mode.
   */
  successDefinition?: 'self' | 'checker-verified'
  /**
   * When provided, each entry's contribution to n and successes is multiplied
   * by an exponential decay weight based on its age relative to `now`.
   *
   * The aggregated LedgerStats rows will have non-null `effectiveN` and
   * `effectiveSuccesses` fields alongside the unchanged raw `n` / `successes`.
   * Absent → effectiveN and effectiveSuccesses are null (raw counts only).
   */
  recency?: RecencyOptions
}

/**
 * Compute the exponential decay weight for a single ledger entry.
 *
 * w = 0.5 ^ (age_days / halfLifeDays)
 *
 * Entries with a missing or unparseable `ts` are treated as age=0 (w=1.0) —
 * conservative: we don't punish entries that simply lack a timestamp.
 *
 * @internal Exported for unit tests only; not part of the public API.
 */
export function decayWeight(entryTs: string | undefined | null, opts: RecencyOptions): number {
  const MS_PER_DAY = 86_400_000
  const ts = entryTs ? Date.parse(entryTs) : NaN
  if (isNaN(ts)) return 1.0
  const ageDays = Math.max(0, (opts.now - ts) / MS_PER_DAY)
  return Math.pow(0.5, ageDays / opts.halfLifeDays)
}

/**
 * Aggregate ledger entries into per-(persona × workload × provider_model_used)
 * success-rate cells.
 *
 * Entries that are missing any of the three key fields are excluded from
 * aggregation; they cannot be attributed to a cell.
 *
 * NOTE: task_category is intentionally excluded from the cell key. Adding it
 * would fragment cells below MIN_RELIABLE_N at current dispatch volumes. The
 * field is captured in each LedgerEntry so future analysis can stratify by
 * category once cell sizes are large enough to support it.
 *
 * @param entries  Raw LedgerEntry array, or AnnotatedLedgerEntry array (from
 *                 joinCheckerVerdicts) when using successDefinition: 'checker-verified'.
 * @param options  Aggregation options.  Defaults: successDefinition='self'.
 *                 Pass `recency` to get exponential-decay-weighted effectiveN /
 *                 effectiveSuccesses alongside the unchanged raw n / successes.
 */
export function aggregateLedgerStats(
  entries: LedgerEntry[],
  options?: AggregateLedgerOptions,
): LedgerStats[] {
  const successDef = options?.successDefinition ?? 'self'
  const recencyOpts = options?.recency
  type CellKey = string
  const cells = new Map<
    CellKey,
    {
      persona: string
      workload: string
      model: string
      n: number
      successes: number
      durations: number[]
      effectiveN: number
      effectiveSuccesses: number
      /** Infrastructure-excluded entry count for observability (route-stats display). */
      infraExcluded: number
    }
  >()

  for (const entry of entries) {
    const persona = entry.persona
    const workload = entry.workload
    const model = entry.provider_model_used
    if (!persona || !workload || !model) continue

    if (successDef === 'checker-verified') {
      // Skip checker rows — they are verdict sources, not outcomes.
      if (persona.endsWith('-checker')) continue
      // Cast: AnnotatedLedgerEntry has checker_goal_met; plain LedgerEntry does not.
      const annotated = entry as AnnotatedLedgerEntry
      // Absent checker verdict → exclude from this aggregation entirely.
      if (!('checker_goal_met' in annotated) || annotated.checker_goal_met === null) continue
    }

    const key = `${persona}\0${workload}\0${model}`
    let cell = cells.get(key)
    if (!cell) {
      cell = { persona, workload, model, n: 0, successes: 0, durations: [], effectiveN: 0, effectiveSuccesses: 0, infraExcluded: 0 }
      cells.set(key, cell)
    }

    // ── Failure-category discrimination ────────────────────────────────────────
    // Infrastructure failures (rate_limited, auth, server_error, timeout) are
    // excluded from n/successes entirely — they carry no model-quality signal.
    // They are tracked in infraExcluded for observability but do not affect the
    // Wilson LCB that drives routing.
    //
    // context_exceeded is NOT excluded: the model genuinely could not handle the
    // task at that context size — this is capability evidence, counts as failure.
    //
    // Legacy rows (failure_category absent/null): counted as today — absence of
    // category does not imply infrastructure failure.
    //
    // NOTE: providerFailover.ts classifyFailoverReason() fires on API errors
    // before a persona dispatch completes, so failover-driven retries never
    // produce persona YAML.  failure_category here is persona-level
    // self-classification only — no double-counting with the failover path.
    const fc = entry.failure_category
    if (fc !== undefined && fc !== null && INFRA_FAILURE_CATEGORIES.has(fc)) {
      cell.infraExcluded++
      continue // exclude from n/successes/durations/effective counts
    }
    // ──────────────────────────────────────────────────────────────────────────

    cell.n++

    const isSuccess = successDef === 'checker-verified'
      ? isSuccessEntry(entry) && (entry as AnnotatedLedgerEntry).checker_goal_met === true
      : isSuccessEntry(entry)

    if (isSuccess) cell.successes++

    if (typeof entry.duration_s === 'number' && entry.duration_s !== null) {
      cell.durations.push(entry.duration_s)
    }

    // Recency-weighted effective counts.
    if (recencyOpts) {
      const w = decayWeight(entry.ts, recencyOpts)
      cell.effectiveN += w
      if (isSuccess) cell.effectiveSuccesses += w
    }
  }

  const result: LedgerStats[] = []
  for (const cell of cells.values()) {
    const avgDurationS =
      cell.durations.length > 0
        ? cell.durations.reduce((a, b) => a + b, 0) / cell.durations.length
        : null
    result.push({
      persona: cell.persona,
      workload: cell.workload,
      provider_model_used: cell.model,
      n: cell.n,
      successes: cell.successes,
      successRate: cell.n > 0 ? cell.successes / cell.n : null,
      avgDurationS,
      effectiveN: recencyOpts ? cell.effectiveN : null,
      effectiveSuccesses: recencyOpts ? cell.effectiveSuccesses : null,
      infraExcluded: cell.infraExcluded,
    })
  }
  return result
}

/**
 * Convenience: read the ledger from `projectRoot` and return aggregated stats.
 * Always uses successDefinition: 'self' (default). For checker-verified aggregation,
 * call readLedgerEntries → joinCheckerVerdicts → aggregateLedgerStats directly.
 */
export function getLedgerStats(projectRoot: string): LedgerStats[] {
  return aggregateLedgerStats(readLedgerEntries(projectRoot))
}
